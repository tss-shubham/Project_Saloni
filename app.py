# ---------------------------------------------------------------------
with st.sidebar:
    conn_ok = _has_api_key()
    dot_cls = "on" if conn_ok else "off"
    conn_text = "Connected via Groq" if conn_ok else "No API key set"
    st.markdown(
        f'<div class="status-pill"><span class="dot {dot_cls}"></span>{conn_text}</div>',
        unsafe_allow_html=True,
    )

    st.markdown("### Document Vault")

    if st.session_state.catalog_sources:
        items = "".join(f"<li>{s}</li>" for s in st.session_state.catalog_sources)
        st.markdown(
            f'<div class="vault-box"><b>Indexed now</b><ul>{items}</ul></div>',
            unsafe_allow_html=True,
        )
    else:
        st.markdown(
            '<div class="vault-box">Vault is empty — add a policy document below.</div>',
            unsafe_allow_html=True,
        )

    uploaded_files = st.file_uploader(
        "Upload bank PDFs — terms & conditions, fee schedules, KYC policy, "
        "product disclosures, account agreements",
        type=["pdf"],
        accept_multiple_files=True,
    )

    col1, col2 = st.columns(2)
    with col1:
        build_clicked = st.button("Build Index", type="primary", use_container_width=True)
    with col2:
        load_clicked = st.button("Load Saved", use_container_width=True)

    k = st.slider("Chunks to retrieve per question", 2, 8, 4)

    if build_clicked:
        if not uploaded_files:
            st.warning("Please upload at least one PDF first.")
        else:
            with st.spinner("Reading documents, chunking, and embedding..."):
                tmp_paths = []
                tmp_dir = tempfile.mkdtemp()
                for f in uploaded_files:
                    path = os.path.join(tmp_dir, f.name)
                    with open(path, "wb") as out:
                        out.write(f.getbuffer())
                    tmp_paths.append(path)

                chunks = load_and_split_pdfs(tmp_paths)
                vectorstore = build_vectorstore(chunks)
                try:
                    chain, retriever = build_rag_chain(vectorstore, k=k)
                    st.session_state.chain = chain
                    st.session_state.retriever = retriever
                    _register_index(vectorstore)
                except RuntimeError as e:
                    st.error(str(e))
                    st.stop()
            st.success(f"Index built from {len(uploaded_files)} file(s), {len(chunks)} chunks.")
            st.rerun()

    if load_clicked:
        if not os.path.exists(INDEX_DIR):
            st.warning("No saved index found yet. Build one first.")
        else:
            with st.spinner("Loading saved index..."):
                vectorstore = load_vectorstore()
                try:
                    chain, retriever = build_rag_chain(vectorstore, k=k)
                    st.session_state.chain = chain
                    st.session_state.retriever = retriever
                    _register_index(vectorstore)
                except RuntimeError as e:
                    st.error(str(e))
                    st.stop()
            st.success("Saved index loaded.")
            st.rerun()

    st.divider()
    st.caption(
        "Rebuild whenever policy documents change. The index is also saved to "
        "disk so you can reload it next time without re-uploading."
    )

